CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ==========================================
-- 1. UTILITY FUNCTIONS
-- ==========================================
CREATE OR REPLACE FUNCTION public.app_check_password(p_plain text, p_hash text) RETURNS boolean
    LANGUAGE sql STABLE
    SET search_path = public, pg_temp
    AS $$ select p_hash is not null and public.crypt(p_plain, p_hash) = p_hash $$;

CREATE OR REPLACE FUNCTION public.app_hash_password(p_plain text) RETURNS text
    LANGUAGE sql
    SET search_path = public, pg_temp
    AS $$ select public.crypt(p_plain, public.gen_salt('bf', 10)) $$;

CREATE OR REPLACE FUNCTION public.app_touch_updated_at() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
    new.updated_at := now();
    return new;
end $$;

-- ==========================================
-- 2. USERS
-- ==========================================
CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL,
    password_hash text NOT NULL,
    role text DEFAULT 'player' NOT NULL,
    fullname text DEFAULT '' NOT NULL,
    photo text DEFAULT 'na.png' NOT NULL,
    email text,
    phone text,
    status text DEFAULT 'active' NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    last_login_at timestamp with time zone,
    is_bot boolean DEFAULT false NOT NULL,
    CONSTRAINT users_role_check CHECK (role IN ('player', 'admin', 'superadmin')),
    CONSTRAINT users_status_check CHECK (status IN ('active', 'suspended')),
    CONSTRAINT users_username_check CHECK (username ~ '^[A-Za-z0-9]{2,20}$')
);

CREATE UNIQUE INDEX users_username_lower_key ON public.users (lower(username));

-- ==========================================
-- 3. GAMES
-- ==========================================
CREATE TABLE public.games (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    host_id bigint NOT NULL REFERENCES public.users(id),
    max_players smallint DEFAULT 6 NOT NULL,
    status text DEFAULT 'lobby' NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    current_suit text,
    top_card_rank text,
    top_card_suit text,
    cutter_rank text,
    cutter_suit text,
    deck_remaining integer DEFAULT 52,
    discard_pile jsonb DEFAULT '[]'::jsonb,
    turn_user_id bigint REFERENCES public.users(id),
    turn_deadline timestamp with time zone,
    direction smallint DEFAULT 1 NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    finished_at timestamp with time zone,
    CONSTRAINT games_status_check CHECK (status IN ('lobby', 'playing', 'finished')),
    CONSTRAINT games_suit_check CHECK (current_suit IN ('hearts', 'diamonds', 'clubs', 'spades')),
    CONSTRAINT games_direction_check CHECK (direction IN (1, -1))
);

CREATE INDEX games_status_updated_idx ON public.games (status, updated_at DESC);
CREATE INDEX games_host_idx ON public.games (host_id);

-- ==========================================
-- 4. GAME PLAYERS
-- ==========================================
CREATE TABLE public.game_players (
    game_id bigint NOT NULL REFERENCES public.games(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.users(id),
    seat smallint NOT NULL,
    joined_at timestamp with time zone DEFAULT now() NOT NULL,
    last_seen timestamp with time zone DEFAULT now() NOT NULL,
    hand_cards jsonb DEFAULT '[]'::jsonb NOT NULL,
    card_count smallint DEFAULT 7 NOT NULL,
    points integer DEFAULT 0 NOT NULL,
    has_cut_card boolean DEFAULT false NOT NULL,
    final_rank smallint,
    left_at timestamp with time zone,
    left_reason text,
    left_by bigint REFERENCES public.users(id),
    CONSTRAINT game_players_pkey PRIMARY KEY (game_id, user_id),
    CONSTRAINT game_players_game_id_seat_key UNIQUE (game_id, seat),
    CONSTRAINT game_players_seat_check CHECK (seat BETWEEN 1 AND 6),
    CONSTRAINT game_players_hand_check CHECK (card_count >= 0)
);

CREATE INDEX game_players_user_idx ON public.game_players (user_id);

-- ==========================================
-- 5. GAME EVENTS
-- ==========================================
CREATE TABLE public.game_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES public.games(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.users(id),
    event_type text NOT NULL,
    payload jsonb,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX game_events_game_idx ON public.game_events (game_id, id);

